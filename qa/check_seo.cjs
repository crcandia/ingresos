// Validate the public source before JavaScript, then verify hydration and export.
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const root=path.resolve(__dirname,'..'),site=path.join(root,'site');
const html=fs.readFileSync(path.join(site,'index.html'),'utf8');
const offline=fs.readFileSync(path.join(root,'Ingresos_Chile_ESI2025.html'),'utf8');
const config=JSON.parse(fs.readFileSync(path.join(root,'interfaz/seo.json'),'utf8'));
const raw=new JSDOM(html),d=raw.window.document;
assert.equal(d.querySelectorAll('h1').length,1);
assert(!html.includes('<!--__INCOME_ANSWERS__-->'));
for(const link of d.querySelectorAll('.topic-links a,.faq a[href^="#"]'))assert(d.getElementById(link.getAttribute('href').slice(1)),'Broken topic link');
assert(d.querySelector('.faq-scope').textContent.includes('no cambian con los filtros'));
assert(d.getElementById('sueldo-promedio-chile').textContent.includes('$967.862'));
assert(d.getElementById('sueldo-mediano-chile').textContent.includes('$688.209'));
assert(d.getElementById('personas-un-millon').textContent.includes('29,6%'));
assert(d.getElementById('personas-un-millon').textContent.includes('2.651.000'));
assert(d.querySelector('h1').textContent.includes('Ingresos en Chile'));
assert.equal(d.title,config.title);
assert.equal(d.querySelector('meta[name="description"]').content,config.description);
assert.equal(d.querySelectorAll('link[rel="canonical"]').length,1);
assert.equal(d.querySelector('link[rel="canonical"]').href,config.canonical);
assert(!d.querySelector('meta[name="robots"]').content.includes('noindex'));
const meta=key=>d.querySelector(`meta[property="${key}"],meta[name="${key}"]`)?.content;
for(const key of ['og:title','og:type','og:url','og:description','og:image','og:image:width','og:image:height','og:image:alt','twitter:card','twitter:title','twitter:description','twitter:image','twitter:image:alt'])assert(meta(key),key);
assert.equal(meta('og:url'),config.canonical);
assert.equal(meta('twitter:card'),'summary_large_image');
assert.equal(meta('twitter:image'),meta('og:image'));
const image=fs.readFileSync(path.join(site,config.image));
assert.equal(image.readUInt32BE(16),+meta('og:image:width'));
assert.equal(image.readUInt32BE(20),+meta('og:image:height'));
assert(image.length<5_000_000);
const ids=Array.from(d.querySelectorAll('[id]'),n=>n.id);
assert.equal(new Set(ids).size,ids.length,'Duplicate DOM identifiers');
const initial={};
for(const id of ['median','mean','population','threshold-percent','threshold-people','universe-counts']){
 initial[id]=d.getElementById(id).textContent;
 assert(initial[id].trim().length>0,'Empty initial content '+id);
}
assert.equal(d.querySelectorAll('#age-panels [data-age-panel]').length,12);
assert.equal(d.querySelectorAll('#occupation-ranking [data-rank-occupation]').length,9);
assert(d.querySelector('#distribution svg')&&d.querySelector('#survival svg')&&d.querySelector('#age-profile svg'));
assert.equal(d.querySelectorAll('#age-profile .age-median-point').length,12);
assert.equal(d.querySelectorAll('script[type="application/ld+json"]').length,1);
const structured=JSON.parse(d.getElementById('structured-data').textContent);
assert.equal(structured['@context'],'https://schema.org');
const graph=structured['@graph'];
for(const type of ['WebSite','WebPage','Person','Dataset'])assert(graph.some(x=>x['@type']===type));
assert(!graph.some(x=>['FAQPage','Review','AggregateRating'].includes(x['@type'])));
const dataset=graph.find(x=>x['@type']==='Dataset');
assert(dataset.description.length>=50&&dataset.description.includes('20 años o más'));
assert.equal(dataset.distribution.contentUrl,config.canonical+config.dataset);
assert.equal(dataset.distribution.encodingFormat,'text/csv');
assert(!dataset.license,'Do not invent a dataset license');
assert(d.querySelector('#datos a[download]').href===dataset.distribution.contentUrl);
assert(fs.readFileSync(path.join(site,config.dataset)).equals(fs.readFileSync(path.join(root,'tablas/resumen_dominios.csv'))));
for(const target of [...d.querySelectorAll('link[rel="icon"],link[rel="apple-touch-icon"]')].map(n=>n.href).concat(meta('og:image'),dataset.distribution.contentUrl)){
 const url=new URL(target);assert.equal(url.origin,new URL(config.canonical).origin);
 assert(fs.existsSync(path.join(site,url.pathname)),'Missing public resource '+url.pathname);
}
const sitemap=new JSDOM(fs.readFileSync(path.join(site,'sitemap.xml'),'utf8'),{contentType:'application/xml'});
assert.equal(sitemap.window.document.querySelector('loc').textContent,config.canonical);
assert.equal(sitemap.window.document.querySelector('lastmod').textContent,config.modified);
assert(fs.readFileSync(path.join(site,'robots.txt'),'utf8').includes('Sitemap: '+config.canonical+'sitemap.xml'));
assert.equal(fs.readFileSync(path.join(site,'_redirects'),'utf8'),'/index.html / 301!\n');
assert(new JSDOM(fs.readFileSync(path.join(site,'404.html'),'utf8')).window.document.querySelector('meta[name="robots"]').content.includes('noindex'));
const errors=[],downloads=[];
const make=(source,url)=>new JSDOM(source,{url,runScripts:'dangerously',virtualConsole:new VirtualConsole().on('jsdomError',e=>errors.push(e.message)),beforeParse(w){
 w.HTMLElement.prototype.scrollIntoView=function(){};
 w.Blob=class{constructor(parts){this.parts=parts;}};w.URL.createObjectURL=b=>{downloads.push(b);return'blob:test';};w.URL.revokeObjectURL=()=>{};w.HTMLAnchorElement.prototype.click=function(){};
}});
const active=make(html,config.canonical),a=active.window.document;
for(const [id,text] of Object.entries(initial))assert.equal(a.getElementById(id).textContent,text,'Hydration mismatch '+id);
active.window.ESI_DASHBOARD.setState({occupation:'3',age:'50_54',sex:'1',amount:3000000,survivalScale:'log',rank:'threshold'});
a.getElementById('save').click();
const savedHTML=downloads.at(-1).parts.join('');
const savedStatic=new JSDOM(savedHTML),s=savedStatic.window.document;
for(const id of ['occupation','rank-metric','amount','amount-slider'])assert.equal(s.getElementById(id).value,a.getElementById(id).value,'Saved control differs without JavaScript: '+id);
for(const id of ['selection-label','threshold-percent','threshold-people'])assert.equal(s.getElementById(id).textContent,a.getElementById(id).textContent,'Saved result differs without JavaScript: '+id);
const copy=make(savedHTML,'file:///ingresos.html'),c=copy.window.document;
assert.equal(c.querySelectorAll('[data-web-meta],[data-web-analytics],script[src],link[rel="icon"],link[rel="apple-touch-icon"]').length,0);
assert.equal(c.querySelectorAll('link[rel="canonical"]').length,0);
assert.equal(c.getElementById('structured-data'),null);
assert.equal(copy.window.ESI_DASHBOARD.getState().age,'50_54');
assert.equal(copy.window.ESI_DASHBOARD.getState().survivalScale,'log');
const plain=new JSDOM(offline);
assert.equal(plain.window.document.querySelectorAll('[data-web-meta],[data-web-analytics],script[src]').length,0);
assert(plain.window.document.getElementById('median').textContent.length>0);
assert.equal(d.getElementById('dashboard-data').textContent,plain.window.document.getElementById('dashboard-data').textContent);
assert.equal(errors.length,0,errors.join('\n'));
const report={pass:true,canonical:config.canonical,socialImage:{width:+meta('og:image:width'),height:+meta('og:image:height'),bytes:image.length},preRenderedInitialView:true,hydrationMatchesSource:true,metadataAndSchemaPassed:true,publicResourcesPresent:true,csvMatchesSource:true,savedCopyRemainsOffline:true,savedControlsMatchWithoutJavaScript:true,statisticalDataUnchanged:true,scope:'Source and DOM checks. No production HTTP, crawler indexing or social platform cache verification.'};
fs.writeFileSync(path.join(__dirname,'validacion_seo.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));[raw,sitemap,active,savedStatic,copy,plain].forEach(x=>x.window.close());
